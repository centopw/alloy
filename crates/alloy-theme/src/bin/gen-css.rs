use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process;

use alloy_theme::{Theme, ThemeLoader, ThemeResolver};
use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]
pub struct ContrastSummary {
    pub passes_aa: bool,
    pub passes_aaa: bool,
    pub checks_count: usize,
    pub failures: Vec<String>,
}

#[derive(Serialize, Deserialize, Debug, Clone, PartialEq)]
pub struct ThemeManifestEntry {
    pub id: String,
    pub name: String,
    pub mode: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub author: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub version: Option<String>,
    pub passes_aa: bool,
    pub passes_aaa: bool,
    pub contrast: ContrastSummary,
}

/// Locates the Alloy workspace root directory.
pub fn find_workspace_root() -> Result<PathBuf, String> {
    // 1. Try CARGO_MANIFEST_DIR (points to crates/alloy-theme)
    if let Ok(manifest_dir) = std::env::var("CARGO_MANIFEST_DIR") {
        let path = PathBuf::from(manifest_dir);
        if let Some(parent) = path
            .parent()
            .and_then(|p| p.parent())
            .filter(|p| p.join("packages/themes").exists())
        {
            return Ok(parent.to_path_buf());
        }
    }

    // 2. Try current working directory or ancestors
    let mut current = std::env::current_dir().map_err(|e| e.to_string())?;
    loop {
        if current.join("packages/themes").exists() && current.join("Cargo.toml").exists() {
            return Ok(current);
        }
        if !current.pop() {
            break;
        }
    }

    // 3. Fallback to compile-time CARGO_MANIFEST_DIR
    let compile_time_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    if let Some(parent) = compile_time_dir
        .parent()
        .and_then(|p| p.parent())
        .filter(|p| p.join("packages/themes").exists())
    {
        return Ok(parent.to_path_buf());
    }

    Err("Could not locate Alloy workspace root (containing packages/themes)".into())
}

/// Discovers, loads, resolves all themes, and returns (css_content, manifest_entries).
pub fn generate(workspace_root: &Path) -> Result<(String, Vec<ThemeManifestEntry>), String> {
    let themes_dir = workspace_root.join("packages/themes");

    let mut resolver = ThemeResolver::new();
    let mut themes_map: BTreeMap<String, Theme> = BTreeMap::new();

    // 1. Builtins from alloy-theme
    let builtins = [
        alloy_theme::alloy_light(),
        alloy_theme::alloy_dark(),
        alloy_theme::alloy_amoled(),
    ];
    for b in builtins {
        themes_map.insert(b.id.clone(), b);
    }

    // 2. Discover and register all themes in packages/themes/*.json / *.jsonc
    if themes_dir.exists() {
        let entries = fs::read_dir(&themes_dir)
            .map_err(|e| format!("Failed to read themes dir {:?}: {}", themes_dir, e))?;

        let mut file_paths = Vec::new();
        for entry in entries {
            let entry = entry.map_err(|e| e.to_string())?;
            let path = entry.path();
            if path
                .extension()
                .is_some_and(|ext| ext == "json" || ext == "jsonc")
            {
                file_paths.push(path);
            }
        }
        file_paths.sort();

        for path in file_paths {
            let theme = ThemeLoader::load_from_path(&path)
                .map_err(|e| format!("Failed to load theme from {:?}: {}", path, e))?;
            resolver.register(theme.clone());
            themes_map.insert(theme.id.clone(), theme);
        }
    }

    // Register all discovered themes so resolution of extends works across all
    for theme in themes_map.values() {
        resolver.register(theme.clone());
    }

    // 3. Generate scoped CSS and manifest
    let mut css_lines = Vec::new();
    css_lines.push("/* Auto-generated by alloy-theme (gen-css). DO NOT EDIT MANUALLY. */".into());
    css_lines.push("/* Run: cargo run -p alloy-theme --bin gen-css */\n".into());

    let mut manifest = Vec::new();

    for (id, theme) in &themes_map {
        let resolved = resolver
            .resolve(theme)
            .map_err(|e| format!("Failed to resolve theme '{}': {}", id, e))?;

        // CSS scoping
        css_lines.push(format!("[data-theme=\"{}\"] {{", id));
        for (var_name, value) in resolved.css_vars() {
            css_lines.push(format!("  {}: {};", var_name, value));
        }
        css_lines.push("}\n".into());

        // Contrast summary
        let failures: Vec<String> = resolved
            .contrast_report
            .failures()
            .iter()
            .map(|f| {
                format!(
                    "{} ({} on {}): ratio {:.2} < min {:.2}",
                    f.name, f.foreground_name, f.background_name, f.ratio, f.min_aa
                )
            })
            .collect();

        let passes_aa = resolved.contrast_report.passes_aa;
        let passes_aaa = resolved.contrast_report.passes_aaa;
        let checks_count = resolved.contrast_report.checks.len();

        manifest.push(ThemeManifestEntry {
            id: id.clone(),
            name: theme.name.clone(),
            mode: theme.mode.to_string(),
            author: if theme.author.is_empty() {
                None
            } else {
                Some(theme.author.clone())
            },
            version: if theme.version.is_empty() {
                None
            } else {
                Some(theme.version.clone())
            },
            passes_aa,
            passes_aaa,
            contrast: ContrastSummary {
                passes_aa,
                passes_aaa,
                checks_count,
                failures,
            },
        });
    }

    let css_content = css_lines.join("\n");
    Ok((css_content, manifest))
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let check_mode = args.iter().any(|arg| arg == "--check");

    let workspace_root = match find_workspace_root() {
        Ok(root) => root,
        Err(e) => {
            eprintln!("Error: {}", e);
            process::exit(1);
        }
    };

    let target_dir = workspace_root.join("apps/alloy/ui/src/lib/theme/generated");
    let css_path = target_dir.join("themes.css");
    let manifest_path = target_dir.join("themes.json");

    let (css_content, manifest) = match generate(&workspace_root) {
        Ok(res) => res,
        Err(e) => {
            eprintln!("Error generating themes: {}", e);
            process::exit(1);
        }
    };

    let manifest_json = match serde_json::to_string_pretty(&manifest) {
        Ok(mut json) => {
            json.push('\n');
            json
        }
        Err(e) => {
            eprintln!("Error serializing manifest JSON: {}", e);
            process::exit(1);
        }
    };

    if check_mode {
        let existing_css = match fs::read_to_string(&css_path) {
            Ok(content) => content,
            Err(_) => {
                eprintln!(
                    "Error: {} does not exist. Run `cargo run -p alloy-theme --bin gen-css`.",
                    css_path.display()
                );
                process::exit(1);
            }
        };

        let existing_manifest = match fs::read_to_string(&manifest_path) {
            Ok(content) => content,
            Err(_) => {
                eprintln!(
                    "Error: {} does not exist. Run `cargo run -p alloy-theme --bin gen-css`.",
                    manifest_path.display()
                );
                process::exit(1);
            }
        };

        if existing_css != css_content {
            eprintln!(
                "Error: {} is out of date. Run `cargo run -p alloy-theme --bin gen-css`.",
                css_path.display()
            );
            process::exit(1);
        }

        if existing_manifest != manifest_json {
            eprintln!(
                "Error: {} is out of date. Run `cargo run -p alloy-theme --bin gen-css`.",
                manifest_path.display()
            );
            process::exit(1);
        }

        println!("✓ themes.css and themes.json are up to date.");
    } else {
        if let Err(e) = fs::create_dir_all(&target_dir) {
            eprintln!("Error creating directory {:?}: {}", target_dir, e);
            process::exit(1);
        }

        if let Err(e) = fs::write(&css_path, &css_content) {
            eprintln!("Error writing {:?}: {}", css_path, e);
            process::exit(1);
        }

        if let Err(e) = fs::write(&manifest_path, &manifest_json) {
            eprintln!("Error writing {:?}: {}", manifest_path, e);
            process::exit(1);
        }

        println!("✓ Generated themes.css ({} bytes)", css_content.len());
        println!("✓ Generated themes.json ({} themes)", manifest.len());
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_generate_finds_and_resolves_all_themes() {
        let workspace_root = find_workspace_root().expect("workspace root");
        let (css, manifest) = generate(&workspace_root).expect("generate themes");

        assert!(!manifest.is_empty(), "Manifest should contain themes");

        // Verify required builtins
        let ids: Vec<&str> = manifest.iter().map(|m| m.id.as_str()).collect();
        assert!(ids.contains(&"alloy-light"), "Must include alloy-light");
        assert!(ids.contains(&"alloy-dark"), "Must include alloy-dark");
        assert!(ids.contains(&"alloy-amoled"), "Must include alloy-amoled");
        assert!(
            ids.contains(&"midnight-ocean"),
            "Must include midnight-ocean"
        );

        // Verify CSS scoping
        for id in &ids {
            let selector = format!("[data-theme=\"{}\"]", id);
            assert!(
                css.contains(&selector),
                "CSS must contain scoped selector for {}",
                id
            );
        }

        // Verify token variables are generated
        assert!(css.contains("--alloy-color-surface-canvas:"));
        assert!(css.contains("--alloy-color-text-primary:"));
        assert!(css.contains("--alloy-color-accent-primary:"));

        // Verify all pass WCAG AA
        for entry in &manifest {
            assert!(
                entry.passes_aa,
                "Theme '{}' failed WCAG AA: {:?}",
                entry.id, entry.contrast.failures
            );
        }
    }

    #[test]
    fn test_generate_is_deterministic() {
        let workspace_root = find_workspace_root().expect("workspace root");
        let (css1, manifest1) = generate(&workspace_root).expect("generate run 1");
        let (css2, manifest2) = generate(&workspace_root).expect("generate run 2");

        assert_eq!(css1, css2, "CSS output must be byte-for-byte identical");
        assert_eq!(
            manifest1, manifest2,
            "Manifest output must be byte-for-byte identical"
        );
    }
}
